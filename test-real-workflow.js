/**
 * Real End-to-End Workflow Test
 * Tests the actual working components to generate software from PRD
 */

import fs from 'fs-extra';
import path from 'path';
import chalk from 'chalk';

// Import the real agents
import Parser from './src/meta-agents/prd-parser/parser.js';
import { ScaffoldGeneratorAgent } from './src/meta-agents/scaffold-generator/main.js';

async function testRealWorkflow() {
  console.log(chalk.blue('🚀 TESTING REAL PRD TO SOFTWARE WORKFLOW\n'));
  
  const outputDir = path.join(process.cwd(), 'generated-test-project');
  
  // Clean up any previous test output
  await fs.remove(outputDir);
  
  try {
    // Step 1: Define a real PRD in markdown format
    const prdMarkdown = `# Task Management API

## Overview
Build a RESTful API for task management with authentication

## Requirements
- Must have user authentication with JWT (REQ-001)
- Must support CRUD operations for tasks (REQ-002)
- Should have task categories (REQ-003)
- Should support task assignment to users (REQ-004)
- Could have task comments (REQ-005)

## Technical Requirements
- Framework: Express
- Database: MongoDB
- Authentication: JWT
- API Style: REST
`;

    console.log(chalk.blue('📄 PRD Defined: Task Management API\n'));

    // Step 2: Parse PRD with real parser
    console.log(chalk.blue('🔍 Step 1: Parsing PRD with real PRD Parser...'));
    const parser = new Parser();
    const parsed = await parser.parse(prdMarkdown);
    console.log(chalk.green(`✅ Parsed ${parsed.requirements.length} requirements`));
    console.log(chalk.gray(`   High priority: ${parsed.requirements.filter(r => r.priority === 'high').length}`));
    console.log(chalk.gray(`   Medium priority: ${parsed.requirements.filter(r => r.priority === 'medium').length}`));
    console.log(chalk.gray(`   Low priority: ${parsed.requirements.filter(r => r.priority === 'low').length}`));

    // Step 3: Generate scaffold with real scaffold generator
    console.log(chalk.blue('\n🏗️  Step 2: Generating project scaffold...'));
    const scaffoldGenerator = new ScaffoldGeneratorAgent({
      outputDir: outputDir,
      overwrite: true,
      includeTests: true,
      logLevel: 'info'
    });
    
    await scaffoldGenerator.initialize();
    
    // Transform parsed PRD to scaffold input format
    const scaffoldInput = {
      metadata: {
        projectName: "Task Management API",
        version: "1.0.0",
        description: "API for task management with authentication",
        author: "Generated by Meta-Agent Factory"
      },
      tasks: parsed.requirements.map(req => ({
        title: req.title,
        description: req.description,
        priority: req.priority,
        complexity: req.complexity,
        estimatedEffort: req.estimatedEffort
      })),
      dependencies: ["express", "mongodb", "jsonwebtoken", "bcrypt"],
      testFramework: "jest",
      agentType: "backend"
    };
    
    const scaffoldResult = await scaffoldGenerator.process(scaffoldInput);
    console.log(chalk.green('✅ Scaffold generated successfully'));

    // Step 4: Check what was actually generated
    console.log(chalk.blue('\n📁 Step 3: Verifying generated files...'));
    const generatedFiles = await fs.readdir(outputDir, { recursive: true });
    console.log(chalk.green(`✅ Generated ${generatedFiles.length} files`));
    
    // Step 5: Use backend agent to generate API code
    console.log(chalk.blue('\n💻 Step 4: Generating API code with Backend Agent...'));
    
    // Import and use the backend agent directly
    // Import using dynamic import to handle the ES module
    const { BackendAgent } = await import('./src/meta-agents/backend-agent/dist/core/BackendAgent.js');
    
    const backendAgent = new BackendAgent({
      projectRoot: outputDir,
      apiFramework: 'express',
      databaseType: 'mongodb',
      authStrategy: 'jwt',
      logLevel: 'info'
    });
    
    await backendAgent.initialize();
    
    // Generate API based on requirements - now with file writing!
    const apiResult = await backendAgent.generateAPI({
      endpoints: [
        { path: '/auth/register', method: 'POST', handler: 'registerUser' },
        { path: '/auth/login', method: 'POST', handler: 'loginUser' },
        { path: '/tasks', method: 'GET', handler: 'getAllTasks' },
        { path: '/tasks/:id', method: 'GET', handler: 'getTaskById' },
        { path: '/tasks', method: 'POST', handler: 'createTask' },
        { path: '/tasks/:id', method: 'PUT', handler: 'updateTask' },
        { path: '/tasks/:id', method: 'DELETE', handler: 'deleteTask' }
      ],
      framework: 'express',
      authentication: true,
      outputPath: outputDir  // Write files to the generated project directory
    });
    
    console.log(chalk.green(`✅ Generated ${apiResult.generatedFiles?.length || 0} API files`));
    
    // Generate database schemas
    const dbResult = await backendAgent.designDatabase({
      entities: [
        {
          name: 'User',
          fields: [
            { name: 'username', type: 'string', required: true },
            { name: 'email', type: 'string', required: true },
            { name: 'password', type: 'string', required: true }
          ]
        },
        {
          name: 'Task',
          fields: [
            { name: 'title', type: 'string', required: true },
            { name: 'description', type: 'string' },
            { name: 'status', type: 'string', default: 'pending' },
            { name: 'assignedTo', type: 'reference', ref: 'User' },
            { name: 'category', type: 'string' }
          ]
        }
      ],
      relationships: [
        { from: 'Task', to: 'User', type: 'many-to-one', field: 'assignedTo' }
      ],
      outputPath: outputDir  // Write database files to the generated project directory
    });
    
    console.log(chalk.green(`✅ Generated ${dbResult.generatedFiles?.length || 0} database files`));
    
    await backendAgent.shutdown();
    
    // Step 6: Summary
    console.log(chalk.blue('\n📊 WORKFLOW SUMMARY:'));
    console.log(chalk.blue('──────────────────────────────────'));
    console.log(chalk.green(`📄 PRD: Task Management API`));
    console.log(chalk.green(`🔍 Requirements Parsed: ${parsed.requirements.length}`));
    console.log(chalk.green(`🏗️  Scaffold Generated: ${outputDir}`));
    console.log(chalk.green(`💻 API Files Generated: ${apiResult.generatedFiles?.length || 0}`));
    console.log(chalk.green(`🗄️  Database Files Generated: ${dbResult.generatedFiles?.length || 0}`));
    console.log(chalk.green(`📁 Total Files: ${generatedFiles.length}`));
    console.log(chalk.blue('──────────────────────────────────'));
    
    // List some of the generated files
    console.log(chalk.blue('\n📄 Sample Generated Files:'));
    const apiFiles = await fs.readdir(path.join(outputDir, 'src', 'routes'), { recursive: true }).catch(() => []);
    apiFiles.forEach(file => console.log(chalk.gray(`   - src/routes/${file}`)));
    
    return {
      success: true,
      outputPath: outputDir,
      filesGenerated: generatedFiles.length
    };
    
  } catch (error) {
    console.error(chalk.red('\n❌ Workflow failed:'), error.message);
    console.error(error.stack);
    return { success: false, error: error.message };
  }
}

// Run the test
testRealWorkflow()
  .then(result => {
    console.log(chalk.blue('\n🏁 Final Result:'), result);
    if (result.success) {
      console.log(chalk.green('\n✅ REAL CODE GENERATION SUCCESSFUL!'));
      console.log(chalk.yellow(`Check the generated project at: ${result.outputPath}`));
    }
  })
  .catch(err => console.error('Fatal error:', err));